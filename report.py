"""Print the headline out-of-sample tables (Markdown) from results/results.json.

Run:  python3 report.py
The "Headline results" section of README.md was generated by this script, so every number
in it can be regenerated from the committed results file.
"""
from __future__ import annotations

import json
from pathlib import Path

RES = Path(__file__).resolve().parent / "results" / "results.json"
ORDER = ["buy_and_hold", "trend", "meanrev", "hmm_switch", "rules_switch", "hmm_switch_incl_long"]


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    d = json.loads(RES.read_text())
    print(f"Source: results/results.json, generated_utc {d['generated_utc']}\n")
    for root in ("ES", "NQ"):
        s, i = d["summary"][root], d["instruments"][root]
        print(f"#### {root} ({s['ticker']}), out-of-sample {s['oos_range']}, {s['oos_days']} trading days, "
              f"{i['n_refits']} yearly refits\n")
        print("| Strategy | Sharpe (net) | CAGR (net) | Ann. vol | Max drawdown | Time in market "
              "| Sharpe gross | Sharpe at 2x costs |")
        print("|---|---|---|---|---|---|---|---|")
        for k in ORDER:
            print(f"| `{k}` | {s['sharpe_net'][k]:.2f} | {pct(s['cagr_net'][k])} | {pct(s['ann_vol'][k])} "
                  f"| {pct(s['max_drawdown'][k])} | {pct(s['pct_time_in_market'][k])} "
                  f"| {i['sharpe_gross_of_costs'][k]:.2f} | {i['sharpe_at_2x_costs'][k]:.2f} |")
        print("\nSharpe differences, paired stationary block bootstrap (95% interval):\n")
        print("| Comparison | Point | 95% CI |")
        print("|---|---|---|")
        for name, b in i["bootstrap_sharpe_differences"].items():
            print(f"| `{name}` | {b['point']:.2f} | [{b['ci95_low']:.2f}, {b['ci95_high']:.2f}] |")
        od = i["overfit_diagnostic"]
        hs = i["hmm_regime_stats_oos"]
        eps = ", ".join(f"{k} {v['n_episodes']}" for k, v in hs["per_regime"].items())
        print(f"\n* Verdict (HMM switch): {s['verdict_hmm_switch']}.")
        print(f"* Verdict (rules switch): {s['verdict_rules_switch']}.")
        print(f"* HMM switch Sharpe: mean training {od['mean_train_sharpe_hmm_switch']:.2f}, "
              f"mean single-year OOS {od['mean_oos_year_sharpe_hmm_switch']:.2f}, "
              f"full-period OOS {od['full_oos_sharpe_hmm_switch']:.2f}; sleeve choice changed in "
              f"{od['sleeve_choice_changes_across_refits']} of {od['possible_choice_slots']} regime slots across refits.")
        print(f"* OOS HMM regime episodes: {hs['total_episodes']} ({eps}).")
        print(f"* BIC-selected K: {sorted(set(s['k_selected_by_year'].values()))} across all refits.")
        print(f"* Lookahead spot check passed: {s['lookahead_check_all_pass']}.\n")


if __name__ == "__main__":
    main()
